/* Compare immutable main and candidate under the SAME JS/math runtime.
   Frozen Node24 hashes remain checked-in evidence, not portable libm values.
   Expected values are never generated by the candidate conversion code. */
import fs from 'node:fs';import path from 'node:path';import os from 'node:os';import crypto from 'node:crypto';import {execFileSync} from 'node:child_process';
const baseline='42a9d33dd91a3c93cf736e693a86390bef80c61b',driver=new URL('./consolidation-oracle.mjs',import.meta.url);
export async function baselineReference(){
 const root=path.resolve('.'),key=crypto.createHash('sha256').update(baseline+process.version+process.versions.v8+process.platform+process.arch).update(fs.readFileSync(driver)).digest('hex'),cache=path.join(root,'.cache','consolidation-reference-'+key+'.json');
 if(fs.existsSync(cache))return JSON.parse(fs.readFileSync(cache));
 const tmp=fs.mkdtempSync(path.join(os.tmpdir(),'filmlabb-frozen-main-')),checkout=path.join(tmp,'main');
 try{
  execFileSync('git',['worktree','add','--detach',checkout,baseline],{cwd:root,stdio:'pipe'});
  fs.mkdirSync(path.join(checkout,'tools'),{recursive:true});fs.copyFileSync(driver,path.join(checkout,'tools/consolidation-oracle.mjs'));
  fs.mkdirSync(path.join(checkout,'tests/fixtures/consolidation'),{recursive:true});
  const message=execFileSync(process.execPath,['tools/consolidation-oracle.mjs','--capture'],{cwd:checkout,encoding:'utf8',maxBuffer:2**20});
  const reference=JSON.parse(fs.readFileSync(path.join(checkout,'tests/fixtures/consolidation/oracle.json')));
  if(reference.baseline!==baseline||reference.rows.length!==2241||reference.runtime.node!==process.version)throw Error('Frozen main reference identity mismatch');
  const frozen=JSON.parse(fs.readFileSync(path.join(root,'tests/fixtures/consolidation/oracle.json'))),shape=rows=>JSON.stringify(rows.map(({hash,...row})=>row));
  if(shape(reference.rows)!==shape(frozen.rows))throw Error('Frozen reference case coverage changed');
  fs.mkdirSync(path.dirname(cache),{recursive:true});const staging=cache+'.'+process.pid;fs.writeFileSync(staging,JSON.stringify(reference));fs.renameSync(staging,cache);console.log(message.trim(),'from immutable main under',process.version);
  return reference;
 }finally{
  if(fs.existsSync(checkout))execFileSync('git',['worktree','remove','--force',checkout],{cwd:root,stdio:'pipe'});
  fs.rmSync(tmp,{recursive:true,force:true});
 }
}
